/**
 * Helper: Get area by slug
 */
export const getAreaBySlug = (slug: string): Area | undefined =>
  areas.find((a) => a.slug === slug);

/**
 * Helper: Get related areas (same group)
 */
export const getRelatedAreas = (currentSlug: string, limit = 4): Area[] => {
  const current = getAreaBySlug(currentSlug);
  if (!current) return [];
  return areas
    .filter((a) => a.slug !== currentSlug && a.group === current.group)
    .slice(0, limit);
};